"""Writes src/tunnel_roof.inc for Island Skies: for each of the Tunnel's six world blocks, the height of
its ceiling over a grid of cells in the block's own frame, read from the decompilation's block meshes,
so the mod can tell a corner under the roof (the cave, lit by the hour alone) from one under the open
sky (the weather's). A ceiling is a face that faces down (the painted sky's lid, which faces down too,
is told by its size); the cell keeps the highest such face over it, in sixteenths of a unit, 0 where no
ceiling stands. With the grids go the pictures the cave's faces draw with, which the mod leaves as
they are under snow (the open air's pictures are lifted toward white), since the cave shows them too.

    python3 tools/gen_tunnel_roof.py <decompilation dir, e.g. ~/pokemonsnap>

The vertex arrays' addresses are the US ROM's (build/pokemonsnap.map: tunnel_blockN_vtx); a picture's
address is in its symbol's name (D_801585F0_...)."""
import os
import re
import sys

CELL = 50                       # a cell's side, in the game's units
DOWN = -0.35                    # a face is a ceiling when its normal's y, of its length, is below this
SKY_EDGE = 3000                 # a down-facing face with an edge this long is the painted sky's lid, not a ceiling
BLOCKS = [                      # tunnel_blockN_vtx in the game's memory
    0x8011F130, 0x801211A0, 0x80123E60, 0x801278D0, 0x8012A380, 0x8012C100,
]


def read_block(base):
    """The block's vertices and triangles, each triangle with the picture it draws with: (format,
    picture address, palette address), from the decompilation's model and draw files."""
    vtx = [(int(a), int(b), int(c)) for a, b, c in
           re.findall(r'\{\{\{\s*(-?\d+),\s*(-?\d+),\s*(-?\d+)\s*\}', open(base + '/model.vtx.inc.c').read())]
    cache = [None] * 64
    tris = []
    fmt, image, tlut, last_rgba = None, None, None, None
    for line in open(base + '/draw.gfx.inc.c'):
        m = re.search(r'gsDPSetTextureImage\(G_IM_FMT_(\w+),[^,]+,[^,]+,\s*(\w+)\)', line)
        if m:
            addr = symbol_address(m.group(2))
            if m.group(1) == 'RGBA':
                last_rgba = addr
            fmt, image = m.group(1), addr
            continue
        if 'gsDPLoadTLUT' in line:
            tlut = last_rgba
            continue
        m = re.search(r'gsSPVertex\(&\w+\[(\d+)\],\s*(\d+),\s*(\d+)\)', line)
        if m:
            n, count, start = int(m.group(1)), int(m.group(2)), int(m.group(3))
            for i in range(count):
                cache[start + i] = vtx[n + i]
            continue
        found = [(int(a), int(b), int(c)) for a, b, c in re.findall(r'gsSP1Triangle\(\s*(\d+),\s*(\d+),\s*(\d+),', line)]
        for a, b, c, d, e, f in re.findall(r'gsSP2Triangles\(\s*(\d+),\s*(\d+),\s*(\d+),\s*\d+,\s*(\d+),\s*(\d+),\s*(\d+),', line):
            found += [(int(a), int(b), int(c)), (int(d), int(e), int(f))]
        for a, b, c in found:
            t = (cache[a], cache[b], cache[c])
            if None not in t:
                tris.append((t, (fmt, image, tlut if fmt == 'CI' else None)))
    return vtx, tris


def symbol_address(name):
    m = re.match(r'D_([0-9A-Fa-f]{8})', name)
    return int(m.group(1), 16) if m else None


def normal_y(tri):
    (ax, ay, az), (bx, by, bz), (cx, cy, cz) = tri
    ux, uy, uz = bx - ax, by - ay, bz - az
    vx, vy, vz = cx - ax, cy - ay, cz - az
    nx, ny, nz = uy * vz - uz * vy, uz * vx - ux * vz, ux * vy - uy * vx
    length = (nx * nx + ny * ny + nz * nz) ** 0.5
    return ny / length if length > 0 else 0.0


def longest_edge(tri):
    pts = [(p[0], p[2]) for p in tri]
    return max(((pts[i][0] - pts[j][0]) ** 2 + (pts[i][1] - pts[j][1]) ** 2) ** 0.5 for i, j in ((0, 1), (1, 2), (0, 2)))


def overlaps(tri, x0, z0, x1, z1):
    """Whether a triangle (seen from above) and a cell's rectangle overlap: the separating axis test."""
    pts = [(p[0], p[2]) for p in tri]
    rect = [(x0, z0), (x1, z0), (x1, z1), (x0, z1)]
    axes = [(1, 0), (0, 1)]
    for i in range(3):
        (px, pz), (qx, qz) = pts[i], pts[(i + 1) % 3]
        axes.append((-(qz - pz), qx - px))
    for ax, az in axes:
        if ax == 0 and az == 0:
            continue
        a = [ax * x + az * z for x, z in pts]
        b = [ax * x + az * z for x, z in rect]
        if max(a) < min(b) or max(b) < min(a):
            return False
    return True


def main():
    decomp = os.path.expanduser(sys.argv[1])
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'tunnel_roof.inc')
    lines = [
        '// Generated by tools/gen_tunnel_roof.py from the decompilation\'s Tunnel block meshes; do not edit.',
        '// For each block: its vertex array in the game\'s memory and, over a grid of %d-unit cells in the' % CELL,
        '// block\'s own frame, the height of its ceiling (the highest face that faces down there, in',
        '// sixteenths of a unit; 0 where the sky stands open). A corner at or under that height is in',
        '// the cave.',
        '#define TUNNEL_ROOF_CELL %d' % CELL,
        '#define TUNNEL_ROOF_BLOCKS %d' % len(BLOCKS),
        'typedef struct TunnelRoof {',
        '    u32 vtx_lo;',
        '    u32 vtx_hi;',
        '    s16 x0;',
        '    s16 z0;',
        '    u16 w;',
        '    u16 h;',
        '    u8 open_sky;          // the block has faces of the painted sky: the open air is where no ceiling stands',
        '    s16 sky_y_lo;         // the painted sky, its lowest and highest corners (the horizon ring and the lid)',
        '    s16 sky_y_hi;',
        '    const u8* cells;',
        '} TunnelRoof;',
    ]
    entries = []
    cave_pictures = set()
    sky_pictures = set()
    for b, addr in enumerate(BLOCKS):
        vtx, tris = read_block(os.path.join(decomp, 'assets', 'tunnel', 'block%d' % b))
        down = [t for t, pic in tris if normal_y(t) < DOWN and longest_edge(t) < SKY_EDGE]
        block_sky = 0
        sky_ys = []
        for t, pic in tris:
            if normal_y(t) < DOWN and longest_edge(t) >= SKY_EDGE and pic[1] is not None:
                sky_pictures.add(pic[1])
                block_sky = 1
        for t, pic in tris:
            if block_sky and pic[1] in sky_pictures:
                sky_ys.extend(p[1] for p in t)
        sky_lo, sky_hi = (min(sky_ys), max(sky_ys)) if sky_ys else (0, 0)
        if not down:
            lines.append('static const u8 tunnel_roof_cells%d[] = { 0 };' % b)
            entries.append('    { 0x%08Xu, 0x%08Xu, 0, 0, 0, 0, %d, %d, %d, tunnel_roof_cells%d },' % (addr, addr + 16 * len(vtx), block_sky, sky_lo, sky_hi, b))
            print('block %d: %d vertices, %d triangles, no ceiling' % (b, len(vtx), len(tris)))
            continue
        xs = [p[0] for t in down for p in t]
        zs = [p[2] for t in down for p in t]
        x0 = (min(xs) // CELL) * CELL
        z0 = (min(zs) // CELL) * CELL
        w = (max(xs) - x0) // CELL + 1
        h = (max(zs) - z0) // CELL + 1
        cells = [0] * (w * h)
        for t in down:
            top = max(p[1] for p in t)
            value = min(255, max(1, (top + 15) // 16))
            cx0 = max(0, (min(p[0] for p in t) - x0) // CELL)
            cx1 = min(w - 1, (max(p[0] for p in t) - x0) // CELL)
            cz0 = max(0, (min(p[2] for p in t) - z0) // CELL)
            cz1 = min(h - 1, (max(p[2] for p in t) - z0) // CELL)
            for cz in range(cz0, cz1 + 1):
                for cx in range(cx0, cx1 + 1):
                    rx0, rz0 = x0 + cx * CELL, z0 + cz * CELL
                    if overlaps(t, rx0, rz0, rx0 + CELL, rz0 + CELL):
                        i = cz * w + cx
                        cells[i] = max(cells[i], value)

        def under_roof(p):
            if not block_sky:
                return True     # no sky over this block: all of it is cave
            cx, cz = (p[0] - x0) // CELL, (p[2] - z0) // CELL
            if p[0] < x0 or p[2] < z0 or cx >= w or cz >= h:
                return False
            top = cells[cz * w + cx]
            return top != 0 and p[1] <= top * 16 + 16

        cave_faces = 0
        for t, pic in tris:
            is_ceiling = normal_y(t) < DOWN and longest_edge(t) < SKY_EDGE
            if is_ceiling or all(under_roof(p) for p in t):
                cave_faces += 1
                key = pic[2] if pic[0] == 'CI' else pic[1]
                if key is not None:
                    cave_pictures.add(key)
        roofed = sum(1 for c in cells if c)
        print('block %d: %d vertices, %d triangles, %d ceilings, %d cave faces, sky faces %s (y %d..%d); grid %dx%d from (%d, %d), %d cells roofed'
              % (b, len(vtx), len(tris), len(down), cave_faces, 'yes' if block_sky else 'no', sky_lo, sky_hi, w, h, x0, z0, roofed))
        lines.append('static const u8 tunnel_roof_cells%d[] = {' % b)
        for cz in range(h):
            lines.append('    ' + ' '.join('%d,' % c for c in cells[cz * w:(cz + 1) * w]))
        lines.append('};')
        entries.append('    { 0x%08Xu, 0x%08Xu, %d, %d, %d, %d, %d, %d, %d, tunnel_roof_cells%d },' % (addr, addr + 16 * len(vtx), x0, z0, w, h, block_sky, sky_lo, sky_hi, b))
    lines.append('static const TunnelRoof tunnel_roofs[TUNNEL_ROOF_BLOCKS] = {')
    lines.extend(entries)
    lines.append('};')
    cave_pictures -= sky_pictures
    pictures = sorted(cave_pictures)
    lines.append('// The pictures the cave\'s faces draw with: a palette\'s address for a paletted picture, the')
    lines.append('// picture\'s own for the rest. Under snow these are left as they are.')
    lines.append('#define TUNNEL_CAVE_PICTURES %d' % len(pictures))
    lines.append('static const u32 tunnel_cave_pictures[TUNNEL_CAVE_PICTURES] = {')
    for i in range(0, len(pictures), 6):
        lines.append('    ' + ' '.join('0x%08Xu,' % a for a in pictures[i:i + 6]))
    lines.append('};')
    print('cave pictures:', ' '.join('%08X' % a for a in pictures), '(the sky\'s: %s)' % ' '.join('%08X' % a for a in sorted(sky_pictures)))
    open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
    print('wrote', os.path.normpath(out))


if __name__ == '__main__':
    main()
